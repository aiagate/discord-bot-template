"""Canonical definitions for the AI maid characters."""

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class CharacterDefinition:
    """Describe one character's public identity and conversational scope."""

    character_id: str
    name: str
    position: str
    responsibilities: tuple[str, ...]
    persona: str
    speech_style: str
    avatar_url: str | None = None

    @property
    def display_name(self) -> str:
        """Return the character name with its public position."""
        return f"{self.name}【{self.position}】"


@dataclass(frozen=True, slots=True)
class CharacterRoster:
    """Character identities and shared rules supplied to a conversation."""

    common_style: tuple[str, ...]
    characters: tuple[CharacterDefinition, ...]


